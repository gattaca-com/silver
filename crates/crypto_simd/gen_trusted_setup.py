#!/usr/bin/env python3
"""Writes src/trusted_setup.rs: the setup points the cell verifier needs.

Usage: python3 -I gen_trusted_setup.py <c-kzg>/src/trusted_setup.txt > src/kzg/trusted_setup.rs

The file lists the G1 and G2 point counts, then the G1 Lagrange points, the G2 monomial points
and the G1 monomial points, one hex-encoded compressed point per line.
"""
import sys

G1_POINTS, G2_POINTS, CELL = 4096, 65, 64

lines = open(sys.argv[1]).read().split()
assert lines[:2] == [str(G1_POINTS), str(G2_POINTS)], lines[:2]
g2 = lines[2 + G1_POINTS : 2 + G1_POINTS + G2_POINTS]
g1_monomial = lines[2 + G1_POINTS + G2_POINTS :]
assert len(g1_monomial) == G1_POINTS


def array(hex_point):
    return "[" + ", ".join(f"0x{b:02x}" for b in bytes.fromhex(hex_point)) + "]"


print("// Generated by gen_trusted_setup.py from c-kzg's trusted_setup.txt. Do not edit.")
print()
print(f"pub const G1_MONOMIAL: [[u8; 48]; {CELL}] = [")
for point in g1_monomial[:CELL]:
    print(f"    {array(point)},")
print("];")
print(f"pub const G2_MONOMIAL_0: [u8; 96] = {array(g2[0])};")
print(f"pub const G2_MONOMIAL_{CELL}: [u8; 96] = {array(g2[CELL])};")
