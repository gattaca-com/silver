#!/usr/bin/env python3
"""Writes src/kzg/pairing_lines.rs: the Miller loop's lines for the verifier's two G2 points.

Usage: python3 -I gen_pairing_lines.py src/kzg/setup.rs > src/kzg/pairing_lines.rs

The verifier checks e(P0, G2_S_POW_CELL)·e(P1, G2_NEG_GENERATOR) = 1. Both G2 points are fixed,
so each line of the Miller loop is fixed up to its evaluation at P. The untwist
(X, Y) ↦ (X/w², Y/w³) turns a twist slope λ into λ/w, so the spec's line through T, evaluated
at P = (x, y), is w⁻³·((c, −λ·x, 0) + (0, y, 0)·w) with c = λ·X_T − Y_T. Divided by c, it is
(1, l1·x, 0) + (0, l2·y, 0)·w with l1 = −λ/c and l2 = 1/c. The factor c·w⁻³ dropped lies in
Fp4, a proper subfield of Fp12, so the final exponentiation maps it to 1.
"""
import re
import sys

P = 0x1A0111EA397FE69A4B1BA7B6434BACD764774B84F38512BF6730D2A0F6B0F6241EABFFFEB153FFFFB9FEFFFFFFFFAAAB
# The BLS parameter is x = −X_ABS.
X_ABS = 0xD201000000010000
TWIST_B = (4, 4)
LIMBS, LIMB_BITS = 8, 52


def mul(a, b):
    return ((a[0] * b[0] - a[1] * b[1]) % P, (a[0] * b[1] + a[1] * b[0]) % P)


def add(a, b):
    return ((a[0] + b[0]) % P, (a[1] + b[1]) % P)


def sub(a, b):
    return ((a[0] - b[0]) % P, (a[1] - b[1]) % P)


def inverse(a):
    norm = (a[0] * a[0] + a[1] * a[1]) % P
    assert norm != 0
    n = pow(norm, P - 2, P)
    return (a[0] * n % P, -a[1] * n % P)


def on_curve(point):
    x, y = point
    return mul(y, y) == add(mul(mul(x, x), x), TWIST_B)


def g2_literal(source, name):
    """The affine point `name` of setup.rs, from blst's Montgomery form (R = 2^384)."""
    block = re.search(rf"pub const {name}: blst_p2_affine = (.*?)\n}};", source, re.S).group(1)
    words = [int(word, 16) for word in re.findall(r"0x([0-9a-f]{16})", block)]
    assert len(words) == 24, name
    r_inverse = pow(2**384, P - 2, P)
    fp = [sum(w << (64 * j) for j, w in enumerate(words[6 * k : 6 * k + 6])) * r_inverse % P
          for k in range(4)]
    point = ((fp[0], fp[1]), (fp[2], fp[3]))
    assert on_curve(point), name
    return point


def line(t, slope):
    """(l1, l2) of the line through t with this slope."""
    c_inverse = inverse(sub(mul(slope, t[0]), t[1]))
    return mul(sub((0, 0), slope), c_inverse), c_inverse


def chord(t, r, slope):
    """t + r, from the line through them with this slope."""
    x = sub(sub(mul(slope, slope), t[0]), r[0])
    point = (x, sub(mul(slope, sub(t[0], x)), t[1]))
    assert on_curve(point)
    return point


def lines(q):
    """Each bit of |x| below the top doubles T, then adds q where the bit is set: one line each."""
    out = []
    t = q
    for bit in range(X_ABS.bit_length() - 2, -1, -1):
        slope = mul(mul((3, 0), mul(t[0], t[0])), inverse(add(t[1], t[1])))
        out.append(line(t, slope))
        t = chord(t, t, slope)
        if X_ABS >> bit & 1:
            slope = mul(sub(q[1], t[1]), inverse(sub(q[0], t[0])))
            out.append(line(t, slope))
            t = chord(t, q, slope)
    return out


def limbs(value):
    """Fp8's Montgomery form, value·2^416 mod p, as 52-bit limbs."""
    form = value * 2**416 % P
    return [form >> (LIMB_BITS * j) & ((1 << LIMB_BITS) - 1) for j in range(LIMBS)]


source = open(sys.argv[1]).read()
steps = [lines(g2_literal(source, name)) for name in ("G2_S_POW_CELL", "G2_NEG_GENERATOR")]

print("// Generated by gen_pairing_lines.py from setup.rs's G2 literals. Do not edit.")
print()
print("use crate::bls::fp8::{LANES, Limbs};")
print()
print("/// The Miller loop's lines over the bits of |x|: per bit below the top, a")
print("/// doubling, then an addition where the bit is set. Lanes 0 to 3 hold l1.c0,")
print("/// l1.c1, l2.c0 and l2.c1 for `G2_S_POW_CELL`, lanes 4 to 7 the same for")
print("/// `G2_NEG_GENERATOR`, in Fp8's Montgomery form. At P = (x, y) a line is")
print("/// (1, l1·x, 0) + (0, l2·y, 0)·w: the spec's line, times a factor in Fp4 that")
print("/// the final exponentiation removes.")
print(f"pub const PAIRING_LINES: [[Limbs; LANES]; {len(steps[0])}] = [")
for pair_lines in zip(*steps):
    print("    [")
    for l1, l2 in pair_lines:
        for fp in (l1[0], l1[1], l2[0], l2[1]):
            print("        [" + ", ".join(f"0x{limb:013x}" for limb in limbs(fp)) + "],")
    print("    ],")
print("];")
