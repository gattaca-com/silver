#!/usr/bin/env python3
"""Writes src/portable/constants.rs: the scalar Fp's constants in blst's form (R = 2^384).

Usage: python3 -I gen_portable_constants.py src/bls/constants.rs > src/portable/constants.rs && just fmt

Reads BETA_MONT and FROBENIUS_MONT from bls/constants.rs (Fp8's R' = 2^416 form,
52-bit limbs) and converts them; everything else is computed from p.
"""
import re
import sys

P = 0x1A0111EA397FE69A4B1BA7B6434BACD764774B84F38512BF6730D2A0F6B0F6241EABFFFEB153FFFFB9FEFFFFFFFFAAAB
R = 2**384
source = open(sys.argv[1]).read()


def words(value):
    return [value >> (64 * j) & (2**64 - 1) for j in range(6)]


def lane_value(limbs52):
    return sum(limb << (52 * j) for j, limb in enumerate(limbs52))


def from_fp8_form(limbs52):
    """The value an Fp8 Montgomery form (R' = 2^416) holds."""
    return lane_value(limbs52) * pow(2**416, P - 2, P) % P


def constant(name):
    block = re.search(rf"pub const {name}: [^=]*= (.*?)\n\];", source, re.S).group(1)
    return [int(h, 16) for h in re.findall(r"0x([0-9a-f]+)", block)]


def fp(value):
    return "Fp([" + ", ".join(f"0x{w:016x}" for w in words(value * R % P)) + "])"


beta = from_fp8_form(constant("BETA_MONT"))
assert pow(beta, 3, P) == 1 and beta != 1
frobenius = constant("FROBENIUS_MONT")
assert len(frobenius) == 6 * 2 * 8
gammas = [[from_fp8_form(frobenius[16 * j + 8 * c:16 * j + 8 * c + 8]) for c in range(2)]
          for j in range(6)]
xi = (1, 1)


def fp2_pow(a, e):
    result = (1, 0)
    base = a
    while e:
        if e & 1:
            result = ((result[0] * base[0] - result[1] * base[1]) % P,
                      (result[0] * base[1] + result[1] * base[0]) % P)
        base = ((base[0] * base[0] - base[1] * base[1]) % P, 2 * base[0] * base[1] % P)
        e >>= 1
    return result


for j in range(6):
    assert tuple(gammas[j]) == fp2_pow(xi, j * (P - 1) // 6), j

print("// Generated by gen_portable_constants.py from bls/constants.rs. Do not edit.")
print()
print("//! The scalar Fp's constants, in blst's Montgomery form, R = 2^384.")
print()
print("use crate::portable::fp::Fp;")
print()
print("/// −p⁻¹ mod 2^64.")
print(f"pub const P_INV: u64 = 0x{(-pow(P, -1, 2**64)) % 2**64:016x};")
print("pub const ONE: Fp = " + fp(1) + ";")
print("/// R² mod p: the Montgomery product with it takes a plain value to its form.")
print("pub const R2: [u64; 6] = [" + ", ".join(f"0x{w:016x}" for w in words(R * R % P)) + "];")
print("/// R³ mod p: the Montgomery product with it turns (aR)⁻¹ into a⁻¹R.")
print("pub const R3: [u64; 6] = [" + ", ".join(f"0x{w:016x}" for w in words(R**3 % P)) + "];")
print("/// The curve coefficient b = 4.")
print("pub const FOUR: Fp = " + fp(4) + ";")
print("/// The cube root of unity σ scales x by.")
print("pub const BETA: Fp = " + fp(beta) + ";")
print("/// ξ^(j(p − 1)/6) for w^j, as [c0, c1].")
print("pub const FROBENIUS: [[Fp; 2]; 6] = [")
for j in range(6):
    print(f"    [{fp(gammas[j][0])}, {fp(gammas[j][1])}],")
print("];")
